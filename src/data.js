// 5 000 товаров. Массив создаётся ОДИН раз, вне компонентов, и не меняется.
// Каждый третий товар не в наличии, начиная с «Товар 1».
export const products = Array.from({ length: 5000 }, (_, i) => ({
  id: i + 1,
  title: `Товар ${i + 1}`,
  price: 100 + (i % 50) * 10,
  inStock: i % 3 !== 0,
}));
